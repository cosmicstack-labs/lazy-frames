import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PLUGIN_REGISTRY, pluginFingerprint } from '../packages/engine/dist/index.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'docs', 'plugins');

const esc = (value) => String(value)
  .replaceAll('&', '&amp;')
  .replaceAll('<', '&lt;')
  .replaceAll('>', '&gt;')
  .replaceAll('"', '&quot;');

const badge = (plugin) => plugin.default
  ? '<span class="badge badge-default">Default</span>'
  : plugin.status === 'available'
    ? '<span class="badge badge-live">Available</span>'
    : '<span class="badge badge-scaffold">Scaffold</span>';

const installText = (plugin) => plugin.default ? 'Included by default' : `npx lazy plugin install ${plugin.id}`;

function shell(title, description, body, depth = 0) {
  const prefix = depth === 0 ? '../' : '../../';
  const marketplace = depth === 0 ? '' : '../';
  return `<!doctype html>
<!-- generated by scripts/build-plugin-marketplace.mjs -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="${esc(description)}">
<meta name="theme-color" content="#0D0E12">
<link rel="stylesheet" href="${prefix}styles.css">
<link rel="stylesheet" href="${marketplace}marketplace.css">
<link rel="icon" type="image/svg+xml" href="${prefix}favicon.svg">
</head>
<body>
<nav><div class="brand"><div class="brand-mark"></div><div class="brand-text"><div class="brand-name"><a href="${prefix}index.html">Lazy Frames</a></div><a href="https://cosmicstack.ai" class="brand-byline">by Cosmic Stack</a></div></div><div class="links"><a href="${marketplace}">Plugins</a><a href="${prefix}docs.html">Docs</a><a href="https://github.com/cosmicstack-labs/lazy-frames">GitHub</a></div></nav>
${body}
<script src="${marketplace}marketplace.js"></script>
</body>
</html>
`;
}

const cards = PLUGIN_REGISTRY.map((plugin) => {
  const search = [plugin.name, plugin.provider.name, plugin.category, ...plugin.tags, ...plugin.capabilities].join(' ').toLowerCase();
  return `<article class="market-card" data-plugin-card data-category="${plugin.category}" data-search="${esc(search)}">
  <a class="card-link" href="${plugin.id}/">
    <div class="card-top"><div class="plugin-mark">${esc(plugin.name.slice(0, 2).toUpperCase())}</div><div class="badges">${badge(plugin)}</div></div>
    <div class="card-provider">${esc(plugin.provider.name)} · ${esc(plugin.category)}</div>
    <h2>${esc(plugin.name)}</h2>
    <p>${esc(plugin.description)}</p>
    <div class="tag-row">${plugin.tags.slice(0, 4).map((tag) => `<span>${esc(tag)}</span>`).join('')}</div>
  </a>
  <div class="card-install"><code id="install-${plugin.id}">${esc(installText(plugin))}</code>${plugin.default ? '' : `<button class="copy" data-copy="install-${plugin.id}">Copy</button>`}</div>
</article>`;
}).join('\n');

const categories = ['all', ...new Set(PLUGIN_REGISTRY.map((plugin) => plugin.category))];
const indexBody = `<main class="marketplace-page">
  <header class="market-hero"><div class="eyebrow">Plugin marketplace · ${PLUGIN_REGISTRY.length} reviewed manifests</div><h1>Give the agent<br>new instruments.</h1><p>Discover capability-scoped integrations for voice, storytelling, visuals, audio, and delivery. Every plugin is folder-owned, schema-validated, fingerprinted, and permission-declared.</p></header>
  <section class="market-tools"><label class="search"><span>Search</span><input id="plugin-search" type="search" placeholder="voices, storyboards, stock media…"></label><div class="filters">${categories.map((category) => `<button class="filter${category === 'all' ? ' active' : ''}" data-filter="${category}">${category}</button>`).join('')}</div></section>
  <div class="market-count"><span id="plugin-count">${PLUGIN_REGISTRY.length}</span> plugins</div>
  <section class="market-grid" id="plugin-grid">${cards}</section>
  <section class="security"><h2>Folder-owned. Permission-declared.</h2><p>Contributors work inside one <code>plugins/&lt;id&gt;/</code> folder. The shared schema rejects unknown fields and undeclared scope. Scaffold plugins are installable for evaluation but cannot execute until a reviewed adapter becomes available.</p><p><a href="index.json">Machine registry →</a> · <a href="schema.json">Manifest schema →</a> · <a href="https://github.com/cosmicstack-labs/lazy-frames/tree/main/plugins">Contribute a plugin →</a></p></section>
</main>`;

mkdirSync(out, { recursive: true });
const ids = new Set(PLUGIN_REGISTRY.map((plugin) => plugin.id));
for (const entry of readdirSync(out, { withFileTypes: true })) {
  if (entry.isDirectory() && !ids.has(entry.name) && existsSync(path.join(out, entry.name, 'manifest.json'))) {
    rmSync(path.join(out, entry.name), { recursive: true, force: true });
  }
}
const schema = JSON.parse(readFileSync(path.join(out, 'schema.json'), 'utf8'));
const runtimeFields = Object.keys(PLUGIN_REGISTRY[0]).sort();
const schemaFields = Object.keys(schema.properties).sort();
if (JSON.stringify(runtimeFields) !== JSON.stringify(schemaFields) || JSON.stringify([...schema.required].sort()) !== JSON.stringify(runtimeFields)) {
  throw new Error('docs/plugins/schema.json fields differ from the runtime manifest schema');
}
writeFileSync(path.join(out, 'index.html'), shell('Lazy Frames Plugin Marketplace', 'Browse reviewed, schema-validated Lazy Frames plugins for voice, storytelling, visuals, audio, captions, and delivery.', indexBody));
writeFileSync(path.join(out, 'index.json'), `${JSON.stringify({ apiVersion: 'lazy-frames.cosmicstack.ai/registry/v1', plugins: PLUGIN_REGISTRY }, null, 2)}\n`);

for (const plugin of PLUGIN_REGISTRY) {
  const dir = path.join(out, plugin.id);
  mkdirSync(dir, { recursive: true });
  writeFileSync(path.join(dir, 'manifest.json'), `${JSON.stringify(plugin, null, 2)}\n`);
  const command = `npx lazy plugin install ${plugin.id} -p &lt;project&gt;`;
  const detailBody = `<main class="detail-page">
    <a class="back" href="../">← Plugins</a>
    <header class="detail-hero"><div class="plugin-mark large">${esc(plugin.name.slice(0, 2).toUpperCase())}</div><div><div class="badges">${badge(plugin)}</div><div class="card-provider">${esc(plugin.provider.name)} · ${esc(plugin.category)}</div><h1>${esc(plugin.name)}</h1><p>${esc(plugin.description)}</p></div></header>
    <section class="detail-grid"><div class="detail-main"><h2>${plugin.status === 'available' ? 'Ready for scene-linked work' : 'Installable integration scaffold'}</h2><p>${plugin.status === 'available' ? 'This adapter is implemented and available after its declared credentials are approved for the project.' : 'This manifest can be installed, locked, and evaluated today. Execution remains blocked until its reviewed adapter ships, so a scaffold never silently runs incomplete code.'}</p><h3>Capabilities</h3><div class="tag-row">${plugin.capabilities.map((item) => `<span>${esc(item)}</span>`).join('')}</div><h3>Install</h3><div class="detail-command"><code id="detail-install">${plugin.default ? 'Included by default · run to approve: ' : ''}${command}</code><button class="copy" data-copy="detail-install">Copy</button></div></div>
    <aside class="permission-panel"><h2>Declared scope</h2><dl><dt>Network</dt><dd>${esc(plugin.permissions.networkHosts.join(', ') || 'None')}</dd><dt>Environment</dt><dd>${esc(plugin.permissions.environment.join(', ') || 'None')}</dd><dt>Filesystem</dt><dd>${esc(plugin.permissions.filesystem.join(', ') || 'None')}</dd><dt>Fingerprint</dt><dd class="fingerprint">${pluginFingerprint(plugin)}</dd></dl></aside></section>
    <section class="metadata"><div><span>Version</span><strong>${plugin.version}</strong></div><div><span>Runtime</span><strong>${plugin.runtime.type}</strong></div><div><span>Publisher</span><strong>${esc(plugin.publisher.name)}</strong></div><div><span>Provider</span><strong><a href="${esc(plugin.provider.url)}">${esc(plugin.provider.name)}</a></strong></div></section>
  </main>`;
  writeFileSync(path.join(dir, 'index.html'), shell(`${plugin.name} — Lazy Frames Plugin`, plugin.description, detailBody, 1));
}

console.log(`generated marketplace for ${PLUGIN_REGISTRY.length} plugins`);
